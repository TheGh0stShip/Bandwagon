#include "absolute_branch.hpp"

#include <array>
#include <cassert>
#include <cstdint>

int main() {
  const std::array<std::uint8_t, 16> ordinary = {
      0x3d, 0x60, 0x12, 0x34, 0x39, 0x6b, 0x56, 0x78,
      0x7d, 0x69, 0x03, 0xa6, 0x4e, 0x80, 0x04, 0x20};
  assert(bandwagon::aurora_fixer::EncodeAbsoluteBranch(0x12345678, false) ==
         ordinary);

  const std::array<std::uint8_t, 16> signed_low = {
      0x3d, 0x60, 0x12, 0x35, 0x39, 0x6b, 0x80, 0x00,
      0x7d, 0x69, 0x03, 0xa6, 0x4e, 0x80, 0x04, 0x21};
  assert(bandwagon::aurora_fixer::EncodeAbsoluteBranch(0x12348000, true) ==
         signed_low);
}
