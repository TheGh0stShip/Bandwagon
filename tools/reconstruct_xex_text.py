#!/usr/bin/env python3
"""Generate and verify exact LLVM PowerPC assembly for an extracted XEX text section."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path


INVALID_LINE = re.compile(r"<stdin>:(\d+):\d+: warning: invalid instruction encoding")


def parse_int(value: str) -> int:
    return int(value, 0)


def sanitize_symbol(name: str, offset: int) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_.$]", "_", name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"symbol_{cleaned}"
    return f"{cleaned}__{offset:08x}"


def decode_words(llvm_mc: str, data: bytes) -> list[str]:
    lines = [
        " ".join(f"0x{byte:02x}" for byte in data[offset : offset + 4])
        for offset in range(0, len(data), 4)
    ]
    result = subprocess.run(
        [llvm_mc, "--disassemble", "--triple=powerpc64-unknown-linux-gnu"],
        input="\n".join(lines) + "\n",
        text=True,
        capture_output=True,
        check=True,
    )
    invalid = {int(match.group(1)) - 1 for match in INVALID_LINE.finditer(result.stderr)}
    decoded = [
        line.strip()
        for line in result.stdout.splitlines()
        if line.strip() and line.strip() != ".text"
    ]
    output: list[str] = []
    decoded_index = 0
    for index, offset in enumerate(range(0, len(data), 4)):
        word = data[offset : offset + 4]
        if index in invalid:
            output.append(f".long 0x{int.from_bytes(word, 'big'):08x}")
        else:
            if decoded_index >= len(decoded):
                raise RuntimeError("llvm-mc returned fewer instructions than expected")
            output.append(decoded[decoded_index])
            decoded_index += 1
    if decoded_index != len(decoded):
        raise RuntimeError("llvm-mc returned more instructions than expected")
    return output


def render(data: bytes, symbols: dict[int, list[str]], llvm_mc: str, source: str) -> str:
    decoded = decode_words(llvm_mc, data)
    lines = [
        "/*",
        f" * Exact reconstruction of {source}.",
        f" * Size: {len(data)} bytes; SHA-256: {hashlib.sha256(data).hexdigest()}",
        " * Generated by tools/reconstruct_xex_text.py; do not hand-edit.",
        " */",
        "",
        "        .section .text",
        "        .balign 4",
        "",
    ]
    for index, instruction in enumerate(decoded):
        offset = index * 4
        for name in symbols.get(offset, []):
            lines.append(f"{sanitize_symbol(name, offset)}:")
        word = data[offset : offset + 4]
        lines.append(f"        {instruction:<36} /* 0x{offset:05x}: {word.hex()} */")
    return "\n".join(lines) + "\n"


def assemble_and_verify(source: Path, expected: bytes, llvm_mc: str, llvm_objcopy: str) -> None:
    with tempfile.TemporaryDirectory(prefix="bandwagon-xex-text-") as temporary:
        object_path = Path(temporary) / "text.o"
        binary_path = Path(temporary) / "text.bin"
        subprocess.run(
            [
                llvm_mc,
                "-triple=powerpc64-unknown-linux-gnu",
                "-filetype=obj",
                str(source),
                "-o",
                str(object_path),
            ],
            check=True,
        )
        subprocess.run(
            [llvm_objcopy, "-O", "binary", "--only-section=.text", str(object_path), str(binary_path)],
            check=True,
        )
        actual = binary_path.read_bytes()
    if actual != expected:
        mismatch = next(
            (
                offset
                for offset, pair in enumerate(zip(actual, expected))
                if pair[0] != pair[1]
            ),
            min(len(actual), len(expected)),
        )
        raise SystemExit(f"text reconstruction mismatch at offset 0x{mismatch:x}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("image", type=Path)
    parser.add_argument("function_map", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--raw-offset", type=parse_int, required=True)
    parser.add_argument("--size", type=parse_int, required=True)
    parser.add_argument("--source-label", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    llvm_mc = shutil.which("llvm-mc")
    llvm_objcopy = shutil.which("llvm-objcopy")
    if llvm_mc is None or llvm_objcopy is None:
        raise SystemExit("llvm-mc and llvm-objcopy are required")

    image = args.image.read_bytes()
    end = args.raw_offset + args.size
    if args.raw_offset < 0 or args.size <= 0 or end > len(image) or args.size % 4:
        raise SystemExit("invalid text range")
    text = image[args.raw_offset:end]

    function_map = json.loads(args.function_map.read_text(encoding="utf-8"))
    symbols: dict[int, list[str]] = {}
    for function in function_map["functions"]:
        offset = int(function["section_offset"], 0)
        if 0 <= offset < args.size:
            symbols.setdefault(offset, []).append(function["name"])

    rendered = render(text, symbols, llvm_mc, args.source_label)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != rendered:
            raise SystemExit("checked-in assembly is not reproducible")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8", newline="\n")
    assemble_and_verify(args.output, text, llvm_mc, llvm_objcopy)
    print(
        f"Exact text reconstruction: {len(text)} bytes, "
        f"SHA-256 {hashlib.sha256(text).hexdigest()}"
    )


if __name__ == "__main__":
    main()
