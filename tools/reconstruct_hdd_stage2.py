#!/usr/bin/env python3
"""Reconstruct the HDD Stage2 ROP image and embedded PPC worker exactly."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

from reconstruct_xex_text import assemble_and_verify, decode_words


IMAGE_BASE = 0x7A020000
WORKER_BASE = 0x98030000
WORKER_START = 0x32C8C
WORKER_END = 0x34D94
WORKER_STRINGS = 0x34D9C
TRAILER_DESCRIPTOR = WORKER_START + 0x2600
PROLOGUE = bytes.fromhex("7d8802a6")


def bytes_lines(data: bytes, base_offset: int) -> list[str]:
    lines: list[str] = []
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        values = ", ".join(f"0x{byte:02x}" for byte in chunk)
        lines.append(f"        .byte {values:<94} /* 0x{base_offset + offset:05x} */")
    return lines


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("source_output", type=Path)
    parser.add_argument("map_output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    llvm_mc = shutil.which("llvm-mc")
    llvm_objcopy = shutil.which("llvm-objcopy")
    if not llvm_mc or not llvm_objcopy:
        raise SystemExit("llvm-mc and llvm-objcopy are required")
    data = args.input.read_bytes()
    if len(data) < WORKER_STRINGS or len(data) % 4:
        raise SystemExit("unexpected Stage2 image size")

    starts = {
        offset
        for offset in range(WORKER_START, WORKER_END, 4)
        if data[offset : offset + 4] == PROLOGUE
    }
    starts.add(WORKER_START)
    for offset in range(WORKER_START, WORKER_END, 4):
        word = int.from_bytes(data[offset : offset + 4], "big")
        if word >> 26 != 18 or not (word & 1):
            continue
        displacement = word & 0x03FFFFFC
        if displacement & 0x02000000:
            displacement -= 0x04000000
        instruction = WORKER_BASE + offset - WORKER_START
        target = displacement & 0xFFFFFFFF if word & 2 else (instruction + displacement) & 0xFFFFFFFF
        if WORKER_BASE <= target < WORKER_BASE + WORKER_END - WORKER_START:
            starts.add(WORKER_START + target - WORKER_BASE)
    starts = sorted(starts)
    functions: list[dict[str, object]] = []
    for index, offset in enumerate(starts):
        following = starts[index + 1] if index + 1 < len(starts) else WORKER_END
        functions.append(
            {
                "name": f"fn_{WORKER_BASE + offset - WORKER_START:08X}",
                "section": 1,
                "section_offset": f"0x{offset - WORKER_START:08x}",
                "file_offset": f"0x{offset:08x}",
                "address": f"0x{WORKER_BASE + offset - WORKER_START:08x}",
                "storage_class": 2,
                "size_to_next_symbol": following - offset,
            }
        )
    map_document = {
        "schema": "bandwagon-hdd-stage2-functions-v1",
        "source": str(args.input),
        "source_size": len(data),
        "source_sha256": hashlib.sha256(data).hexdigest(),
        "image_base": f"0x{IMAGE_BASE:08x}",
        "worker_load_address": f"0x{WORKER_BASE:08x}",
        "worker_file_range": f"0x{WORKER_START:x}-0x{WORKER_END:x}",
        "function_count": len(functions),
        "functions": functions,
    }
    map_rendered = json.dumps(map_document, indent=2) + "\n"

    decoded = decode_words(llvm_mc, data[WORKER_START:WORKER_END])
    labels = {int(item["file_offset"], 0): item["name"] for item in functions}
    lines = [
        "/*",
        " * Exact reconstruction of Hdd/PeerPressureExploit-Stage2.bin.",
        f" * Size: {len(data)} bytes; SHA-256: {hashlib.sha256(data).hexdigest()}",
        " * Generated by tools/reconstruct_hdd_stage2.py; do not hand-edit.",
        " */",
        "",
        "        .section .text",
        "        .balign 4",
        "stage2_rop_image:",
    ]
    lines.extend(bytes_lines(data[:WORKER_START], 0))
    lines.append("embedded_worker_code:")
    for index, instruction in enumerate(decoded):
        offset = WORKER_START + index * 4
        if offset in labels:
            lines.append(f"{labels[offset]}:")
        word = data[offset : offset + 4]
        lines.append(f"        {instruction:<36} /* 0x{offset:05x}: {word.hex()} */")
    lines.append("embedded_worker_data:")
    lines.extend(bytes_lines(data[WORKER_END:WORKER_STRINGS], WORKER_END))
    lines.append("embedded_worker_strings:")
    lines.extend(bytes_lines(data[WORKER_STRINGS:TRAILER_DESCRIPTOR], WORKER_STRINGS))
    lines.append("stage2_trailer_descriptor:")
    lines.extend(bytes_lines(data[TRAILER_DESCRIPTOR:], TRAILER_DESCRIPTOR))
    rendered = "\n".join(lines) + "\n"

    if args.check:
        if args.source_output.read_text(encoding="utf-8") != rendered:
            raise SystemExit("checked-in Stage2 assembly is not reproducible")
        if args.map_output.read_text(encoding="utf-8") != map_rendered:
            raise SystemExit("checked-in Stage2 function map is not reproducible")
    else:
        args.source_output.parent.mkdir(parents=True, exist_ok=True)
        args.map_output.parent.mkdir(parents=True, exist_ok=True)
        args.source_output.write_text(rendered, encoding="utf-8", newline="\n")
        args.map_output.write_text(map_rendered, encoding="utf-8", newline="\n")
    assemble_and_verify(args.source_output, data, llvm_mc, llvm_objcopy)
    print(
        f"Exact HDD Stage2 reconstruction: {len(data)} bytes, "
        f"{len(functions)} worker functions, SHA-256 {hashlib.sha256(data).hexdigest()}"
    )


if __name__ == "__main__":
    main()
