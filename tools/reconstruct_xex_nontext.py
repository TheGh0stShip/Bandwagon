#!/usr/bin/env python3
"""Generate exact assembly sources for initialized non-code XEX PE sections."""

from __future__ import annotations

import argparse
import hashlib
import shutil
import struct
import subprocess
import tempfile
from pathlib import Path


SECTION_FLAGS = {
    ".rdata": '"a",@progbits',
    ".pdata": '"a",@progbits',
    ".data": '"aw",@progbits',
}


def pe_sections(image: bytes) -> list[tuple[str, int, int]]:
    if image[:2] != b"MZ":
        raise SystemExit("input is not a PE image")
    pe = struct.unpack_from("<I", image, 0x3C)[0]
    if image[pe : pe + 4] != b"PE\0\0":
        raise SystemExit("missing PE signature")
    count = struct.unpack_from("<H", image, pe + 6)[0]
    optional_size = struct.unpack_from("<H", image, pe + 20)[0]
    table = pe + 24 + optional_size
    result: list[tuple[str, int, int]] = []
    for index in range(count):
        header = table + index * 40
        name = image[header : header + 8].split(b"\0", 1)[0].decode("ascii")
        virtual_size, virtual_address = struct.unpack_from("<II", image, header + 8)
        result.append((name, virtual_address, virtual_size))
    return result


def render_section(name: str, address: int, data: bytes) -> str:
    flags = SECTION_FLAGS[name]
    label = "updater_" + name[1:]
    lines = [f'        .section {name},{flags}', "        .balign 4", f"{label}:"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        values = ", ".join(f"0x{byte:02x}" for byte in chunk)
        lines.append(f"        .byte {values:<94} /* 0x{offset:05x} */")
    lines.extend((f"        .size {label}, .-{label}", ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("image", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--verify-bytes", action="store_true")
    args = parser.parse_args()

    image = args.image.read_bytes()
    wanted = {name: (address, size) for name, address, size in pe_sections(image) if name in SECTION_FLAGS}
    missing = SECTION_FLAGS.keys() - wanted.keys()
    if missing:
        raise SystemExit(f"missing sections: {', '.join(sorted(missing))}")

    rendered_sections: list[str] = []
    summaries: list[str] = []
    for name in SECTION_FLAGS:
        address, size = wanted[name]
        end = address + size
        if end > len(image):
            raise SystemExit(f"{name} virtual range exceeds extracted image")
        data = image[address:end]
        rendered_sections.append(render_section(name, address, data))
        summaries.append(f" * {name}: {size} bytes; SHA-256: {hashlib.sha256(data).hexdigest()}")

    rendered = "\n".join(
        [
            "/*",
            " * Exact reconstruction of initialized Updater.xex non-code sections.",
            *summaries,
            " * Generated by tools/reconstruct_xex_nontext.py; do not hand-edit.",
            " */",
            "",
            *rendered_sections,
        ]
    )
    if not rendered.endswith("\n"):
        rendered += "\n"

    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"generated output differs: {args.output}")
        print(f"Exact non-code reconstruction source verified: {args.output}")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8", newline="\n")
        print("\n".join(summaries))

    if args.verify_bytes:
        llvm_mc = shutil.which("llvm-mc")
        llvm_objcopy = shutil.which("llvm-objcopy")
        if not llvm_mc or not llvm_objcopy:
            raise SystemExit("llvm-mc and llvm-objcopy are required for --verify-bytes")
        with tempfile.TemporaryDirectory(prefix="updater-nontext-") as temporary:
            object_path = Path(temporary) / "nontext.o"
            subprocess.run(
                [llvm_mc, "-triple=powerpc64-unknown-linux-gnu", "-filetype=obj", str(args.output), "-o", str(object_path)],
                check=True,
            )
            for name, (address, size) in wanted.items():
                binary_path = Path(temporary) / f"{name[1:]}.bin"
                subprocess.run(
                    [llvm_objcopy, "-O", "binary", f"--only-section={name}", str(object_path), str(binary_path)],
                    check=True,
                )
                actual = binary_path.read_bytes()
                expected = image[address : address + size]
                if actual != expected:
                    raise SystemExit(f"assembled {name} differs from extracted image")
                print(f"Exact assembled {name}: {len(actual)} bytes, SHA-256 {hashlib.sha256(actual).hexdigest()}")


if __name__ == "__main__":
    main()
