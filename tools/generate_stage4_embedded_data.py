#!/usr/bin/env python3
"""Generate the source-level C++ form of Peer Stage4's embedded patch stream."""

from __future__ import annotations

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "PeerPressure/System/PeerPressureExploit-4thStage.bin"
DEFAULT_OUTPUT = ROOT / "reconstruction/stage4/embedded_data.hpp"
START = 0x380
END = 0x750


def render(data: bytes) -> str:
    stream = data[START:END]
    if len(stream) != END - START or stream[-4:] != b"\xff\xff\xff\xff":
        raise SystemExit("invalid Stage4 patch stream boundary or sentinel")
    lines = [
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace bandwagon::stage4 {",
        "",
        "// Peer-specific bytes from Stage4 file 0x380-0x750. Generated by",
        "// tools/generate_stage4_embedded_data.py; the public clean-HV tail is",
        "// deliberately not duplicated here.",
        f"inline constexpr std::array<std::uint8_t, 0x{len(stream):x}> kEmbeddedPatchStream{{{{",
    ]
    for offset in range(0, len(stream), 12):
        chunk = stream[offset : offset + 12]
        values = ", ".join(f"0x{value:02x}" for value in chunk)
        lines.append(f"    {values},")
    lines += ["}};", "", "}  // namespace bandwagon::stage4", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(args.input.read_bytes())
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"stale generated file: {args.output}")
        print(f"Stage4 embedded C++ data is current: {args.output.relative_to(ROOT)}")
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected, encoding="utf-8", newline="\n")
    print(args.output.relative_to(ROOT))


if __name__ == "__main__":
    main()
